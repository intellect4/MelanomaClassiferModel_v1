# 6. Severity Staging Determination (Stage 0 to Stage 3)
def determine_severity_stage(pred_idx, primary_prob, meta_prob):
    if pred_idx == 0:  # Primary
        if primary_prob >= 85.0:
            stage_code = "Stage 0"
            stage_desc = "In Situ / Low Cellular Atypia"
            stage_color = "#2ca02c"
        else:
            stage_code = "Stage 1"
            stage_desc = "Early Localized Invasive Primary"
            stage_color = "#1f77b4"
    else:  # Metastatic
        if meta_prob < 85.0:
            stage_code = "Stage 2"
            stage_desc = "Regional / Micro-Metastatic Spread"
            stage_color = "#ff7f0e"
        else:
            stage_code = "Stage 3"
            stage_desc = "Macroscopic / High-Grade Metastasis"
            stage_color = "#d62728"

    return stage_code, stage_desc, stage_color

# 7. Processing Routine with Grad-CAM and Staging
def process_slide_with_stage(file_path, true_label):
    img = tifffile.imread(file_path).astype(np.float32)

    if img.ndim == 2:
        img = np.stack([img] * 3, axis=-1)
    elif img.ndim == 3 and img.shape[-1] > 3:
        img = img[:, :, :3]
    elif img.ndim == 3 and img.shape[0] == 3:
        img = np.transpose(img, (1, 2, 0))

    img_min, img_max = img.min(), img.max()
    if img_max > img_min:
        norm_img = (img - img_min) / (img_max - img_min)
    else:
        norm_img = np.zeros_like(img)

    resized_img = cv2.resize(norm_img, (224, 224), interpolation=cv2.INTER_LINEAR)
    tensor_img = torch.tensor(
        np.ascontiguousarray(resized_img).transpose(2, 0, 1),
        dtype=torch.float32
    ).unsqueeze(0).to(device)

    input_tensor = tensor_img.clone().detach().requires_grad_(True)

    with torch.enable_grad():
        logits = model(input_tensor)
        probs = F.softmax(logits, dim=1)
        heatmap_tensor = cam(x=input_tensor)

    pred_idx = torch.argmax(probs, dim=1).item()
    primary_prob = probs[0, 0].item() * 100
    meta_prob = probs[0, 1].item() * 100
    confidence = meta_prob if pred_idx == 1 else primary_prob
    is_correct = (pred_idx == true_label)

    stage_code, stage_desc, stage_color = determine_severity_stage(pred_idx, primary_prob, meta_prob)

    raw_cam = heatmap_tensor[0, 0].cpu().detach().numpy()
    cam_resized = cv2.resize(raw_cam, (224, 224))
    gray = cv2.cvtColor((resized_img * 255).astype(np.uint8), cv2.COLOR_RGB2GRAY)
    _, mask = cv2.threshold(gray, 15, 255, cv2.THRESH_BINARY)
    mask = cv2.GaussianBlur(mask, (7, 7), 0) / 255.0
    clean_cam = cam_resized * mask

    fname = os.path.basename(file_path)
    return resized_img, clean_cam, pred_idx, confidence, is_correct, stage_code, stage_desc, stage_color, fname

