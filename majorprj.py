# 4. Universal File Decoder
def decode_image_bytes(raw_bytes, filename):
    fname = filename.lower()
    if fname.endswith(('.tif', '.tiff')):
        img = tifffile.imread(io.BytesIO(raw_bytes)).astype(np.float32)
    else:
        pil_img = Image.open(io.BytesIO(raw_bytes)).convert('RGB')
        img = np.array(pil_img, dtype=np.float32)

    # Standardize dimensions to (H, W, 3)
    if img.ndim == 2:
        img = np.stack([img] * 3, axis=-1)
    elif img.ndim == 3 and img.shape[-1] > 3:
        img = img[:, :, :3]
    elif img.ndim == 3 and img.shape[0] == 3:
        img = np.transpose(img, (1, 2, 0))

    # Min-max normalization
    i_min, i_max = img.min(), img.max()
    norm_img = (img - i_min) / (i_max - i_min + 1e-8)
    resized_img = cv2.resize(norm_img, (224, 224), interpolation=cv2.INTER_LINEAR)

    tensor = torch.tensor(
        np.ascontiguousarray(resized_img).transpose(2, 0, 1),
        dtype=torch.float32
    ).unsqueeze(0).to(device)

    return resized_img, tensor

# 5. Test-Time Augmentation (TTA)
def evaluate_with_tta(model, tensor_x):
    p1 = F.softmax(model(tensor_x), dim=1)
    p2 = F.softmax(model(torch.flip(tensor_x, dims=[3])), dim=1)
    p3 = F.softmax(model(torch.flip(tensor_x, dims=[2])), dim=1)
    p4 = F.softmax(model(torch.rot90(tensor_x, k=1, dims=[2, 3])), dim=1)
    return (p1 + p2 + p3 + p4) / 4.0

