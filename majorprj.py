class ReadTiffd(MapTransform):
    def __init__(self, keys):
        super().__init__(keys)

    def __call__(self, data):
        d = dict(data)
        for key in self.keys:
            img = tifffile.imread(d[key])

            # Ensure standard float32 numpy array
            img = np.asarray(img, dtype=np.float32)

            # Handle RGBA by dropping the alpha channel
            if img.ndim == 3 and img.shape[-1] == 4:
                img = img[:, :, :3]
            elif img.ndim == 2:  # Single-channel grayscale to 3-channel
                img = np.stack([img] * 3, axis=-1)

            d[key] = img
        return d

